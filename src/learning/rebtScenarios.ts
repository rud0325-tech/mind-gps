import type { LearningChoice, RebtScenario } from './content';

export type RebtPlace = 'school' | 'home';
export interface RebtGroup {
  id: string;
  place: RebtPlace;
  name: string;
  icon: string;
  scenarios: RebtScenario[];
}

type Line = readonly [word: string, sentence: string, icon: string];
type Pair = readonly [Line, Line];
interface ScenarioSpec {
  id: string;
  title: Line;
  thoughts: Pair;
  facts: Pair;
  alternatives: Pair;
  action: Line;
  results: Pair;
  next: Line;
  help: string;
  helped: string;
}

// The three reading levels share each choice's meaning. Icons support, rather
// than replace, the adult's explanation of a social situation in picture mode.
function scenario(place: RebtPlace, spec: ScenarioSpec): RebtScenario {
  const line = (part: string, value: Line, support = false): LearningChoice => ({
    id: `${spec.id}-${part}`, word: value[0], sentence: value[1], icon: value[2],
    ...(support ? { support } : {}),
  });
  const helper = place === 'school' ? '선생님' : '가족';
  const support = (part: string) => line(part, [
    `${helper}께 도움`, `${helper}에게 아직 도움이 필요하다고 말해요.`, '🙋',
  ], true);
  const notice = (part: string) => line(part, [
    '마음 확인', '지금 내 마음을 살펴봐요. 불편한 마음이 남아 있어도 괜찮아요.', '💛',
  ]);
  return {
    ...line('situation', spec.title), id: spec.id,
    thoughts: spec.thoughts.map((value, index) => line(`thought-${index}`, value)),
    checkQuestion: '실제로 있었던 일과 아직 모르는 일을 함께 살펴볼까요?',
    facts: spec.facts.map((value, index) => line(`fact-${index}`, value)),
    alternatives: spec.alternatives.map((value, index) => line(`alternative-${index}`, value)),
    actions: [
      {
        ...line('action-try', spec.action),
        outcomes: [
          {
            ...line('try-result-met', spec.results[0]), unresolved: false,
            next: [notice('try-met-notice'), support('try-met-support')],
          },
          {
            ...line('try-result-unmet', spec.results[1]), unresolved: true,
            next: [line('try-unmet-next', spec.next), support('try-unmet-support')],
          },
        ],
      },
      {
        ...line('action-help', [`${helper}께 도움`, spec.help, '🙋'], true),
        outcomes: [
          {
            ...line('help-result-met', ['함께 방법 찾기', spec.helped, '🤝']), unresolved: false,
            next: [notice('help-met-notice'), support('help-met-support')],
          },
          {
            ...line('help-result-unmet', [
              '아직 도움이 필요해요', `${helper}이 바로 도와주기 어려워요. 아직 도움이 필요해요.`, '⏳',
            ]), unresolved: true,
            next: [
              line('help-unmet-again', ['다시 알리기', `${helper}에게 언제 도와줄 수 있는지 물어봐요.`, '🗣️'], true),
              line('help-unmet-other', [
                '다른 어른께 도움',
                place === 'school'
                  ? '주변에 계신 다른 선생님께 도움을 요청해요.'
                  : '다른 믿을 수 있는 어른에게 도움을 요청해요.',
                '🤝',
              ], true),
            ],
          },
        ],
      },
    ],
  };
}

